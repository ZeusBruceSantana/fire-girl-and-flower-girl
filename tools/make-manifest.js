/* Writes sw-manifest.js: the list of every file the game needs to work without internet.
   The offline helper (sw.js) reads that list and saves a copy of each file on the tablet.
   Run it after adding art or a new file:   node tools/make-manifest.js
   The tests check that the list matches the files on disk, so a stale list fails them.
   No dependencies: plain node. */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const OUT = path.join(root, 'sw-manifest.js');

// Folders whose every file goes in; plus the loose files at the root the page needs.
const FOLDERS = ['art', 'data', 'icons', 'js'];
const ROOT_FILES = ['index.html', 'manifest.webmanifest'];
const ROOT_PATTERN = /^styles.*\.css$/;          // every styles*.css at the root
const SKIP_DIRS = new Set(['tests', 'docs', 'relay', 'tools', '.github', 'node_modules', '.git', '.claude', 'incoming']);   // art/incoming: raw paintings waiting for review, never shipped
const SKIP_FILES = /(^|\/)(sw\.js|sw-manifest\.js|README\.md|LICENSE|.*\.md|\.DS_Store|Thumbs\.db)$/;

/* Every file the game needs offline, as sorted relative paths with forward slashes. */
function listOfflineFiles(base = root) {
  const out = [];
  const walk = (dir, rel) => {
    for (const name of fs.readdirSync(dir).sort()) {
      const full = path.join(dir, name), r = rel ? rel + '/' + name : name;
      const st = fs.statSync(full);
      if (st.isDirectory()) { if (!SKIP_DIRS.has(name) && !name.startsWith('.')) walk(full, r); }
      else if (!SKIP_FILES.test(r) && !name.startsWith('.')) out.push(r);
    }
  };
  for (const name of fs.readdirSync(base).sort()) {
    const full = path.join(base, name);
    if (fs.statSync(full).isDirectory()) continue;
    if (ROOT_FILES.includes(name) || ROOT_PATTERN.test(name)) out.push(name);
  }
  for (const f of FOLDERS) if (fs.existsSync(path.join(base, f))) walk(path.join(base, f), f);
  return [...new Set(out)].sort();
}

/* The list as it should be written to sw-manifest.js. */
function manifestText(files) {
  return `/* GENERATED by tools/make-manifest.js. Do not edit by hand: run  node tools/make-manifest.js
   Every file the game needs offline. sw.js saves a copy of each on the tablet the first time the game opens. */
const SW_FILES = [
${files.map(f => `  ${JSON.stringify(f)},`).join('\n')}
];
`;
}

/* Read the list sw-manifest.js holds right now (empty if there is none). */
function readManifest(file = OUT) {
  if (!fs.existsSync(file)) return [];
  const text = fs.readFileSync(file, 'utf8');
  return [...text.matchAll(/^\s*"([^"]+)",\s*$/gm)].map(m => m[1]);
}

if (require.main === module) {
  const files = listOfflineFiles();
  fs.writeFileSync(OUT, manifestText(files));
  console.log(`sw-manifest.js: ${files.length} files listed.`);
}

module.exports = { listOfflineFiles, manifestText, readManifest, OUT };
